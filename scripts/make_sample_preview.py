"""Draws the depth profile of the bundled Sleep-EDF hypnogram as a small SVG for the start screen.

Provenance: every step comes from public/samples/SC4001EC-Hypnogram.edf (PhysioNet Sleep-EDF Expanded, ODC-By
1.0), clipped to the bundled PSG excerpt (29400 s to 54000 s after the original start). Colours are the app's
depth tints. Usage: python make_sample_preview.py <hypnogram.edf> <out.svg>
"""
import sys
import pyedflib

DEPTH = {'W': 0, 'R': 1, '1': 2, '2': 3, '3': 4, '4': 5}
TINTS = ['#e2eef3', '#c3dbe6', '#98bfd3', '#6a9cba', '#3b6f95', '#1f4a6c']
T0, T1 = 29400.0, 54000.0
W, H = 320, 54
r = pyedflib.EdfReader(sys.argv[1])
on, du, tx = r.readAnnotations()
x = lambda t: (min(max(t, T0), T1) - T0) / (T1 - T0) * W
band = H / 6
parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" '
         f'aria-label="Sleep stages of the sample night"><desc>Generated by scripts/make_sample_preview.py from '
         f'SC4001EC-Hypnogram.edf (PhysioNet Sleep-EDF Expanded, ODC-By 1.0).</desc>',
         f'<rect width="{W}" height="{H}" fill="#eadfc2"/>']
line = []
for o, d, t in zip(on, du, tx):
    st = str(t).replace('Sleep stage ', '')
    if o + d <= T0 or o >= T1 or st not in DEPTH:
        continue
    a, b = x(o), x(o + d)
    k = DEPTH[st]
    for j in range(k + 1):
        parts.append(f'<rect x="{a:.2f}" y="{j * band:.2f}" width="{b - a + 0.3:.2f}" height="{band + 0.3:.2f}" fill="{TINTS[j]}"/>')
    y = (k + 1) * band - 0.75
    line += [(a, y), (b, y)]
pts = ' '.join(f'{px:.2f},{py:.2f}' for px, py in line)
parts.append(f'<polyline points="{pts}" fill="none" stroke="#18222e" stroke-width="1.5" stroke-linejoin="round"/>')
parts.append('</svg>')
open(sys.argv[2], 'w').write('\n'.join(parts) + '\n')
print('wrote', sys.argv[2], len(line) // 2, 'epochs')
